    private void btnDeshacerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeshacerActionPerformed
        Pedido ultimo = restaurante.getUltimoAgregado();
        if (ultimo == null) {
            info("No hay pedidos en el historial.");
            return;
        }
        if (!restaurante.puedeDeshacerUltimo()) {
            new FormDetallePedido(this, "Eliminar último pedido",
                "Este pedido ya fue atendido, por ende no se puede eliminar.", ultimo, null).setVisible(true);
            return;
        }
        FormDetallePedido form = new FormDetallePedido(this, "Eliminar último pedido",
            "Último pedido agregado. ¿Seguro que desea eliminarlo?", ultimo, "Eliminar pedido");
        form.setVisible(true);
        if (form.isConfirmado()) {
            restaurante.deshacerUltimoPedidoAgregado();
            info("Pedido eliminado correctamente.");
        }
        refrescar();
    }//GEN-LAST:event_btnDeshacerActionPerformed

    private void btnAtenderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtenderActionPerformed
        Pedido siguiente = restaurante.verSiguientePedido();
        if (siguiente == null) {
            info("No hay pedidos pendientes.");
            return;
        }
        FormDetallePedido form = new FormDetallePedido(this, "Atender siguiente pedido",
            "Siguiente pedido en la cola:", siguiente, "Atender pedido");
        form.setVisible(true);
        if (form.isConfirmado()) {
            restaurante.atenderSiguientePedido();
            info("Pedido #" + siguiente.getNumero() + " atendido.");
        }
        refrescar();
    }//GEN-LAST:event_btnAtenderActionPerformed

