    // Vuelve a llenar la tabla y el total con lo que tiene el pedido
    private void refrescar() {
        DefaultTableModel modelo = (DefaultTableModel) tblDetalle.getModel();
        modelo.setRowCount(0);
        for (DetallePedido d : pedido.getDetalles()) {
            modelo.addRow(new Object[]{
                d.getProducto().getNombre(), d.getCantidad(),
                Producto.moneda(d.getProducto().getPrecio()), Producto.moneda(d.calcularSubtotal())});
        }
        jLabel1.setText("Total: " + Producto.moneda(pedido.calcularTotal()));
    }

