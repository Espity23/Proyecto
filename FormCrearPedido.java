    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        pedido.agregarProducto((Producto) cmbProducto.getSelectedItem(), (Integer) spnCantidad.getValue());
        spnCantidad.setValue(1);
        refrescar();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int fila = tblDetalle.getSelectedRow();
        if (fila < 0) {
            aviso("Seleccione un producto de la tabla.");
            return;
        }
        pedido.quitarDetalle(fila);
        refrescar();
    }//GEN-LAST:event_btnQuitarActionPerformed

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
         if (pedido.getDetalles().isEmpty()) {
            aviso("Agregue al menos un producto al pedido.");
            return;
        }
        restaurante.agregarPedido(pedido);
        JOptionPane.showMessageDialog(this, "Pedido #" + pedido.getNumero() + " agregado a la cola.",
            "FoodFlow", JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        if (!pedido.getDetalles().isEmpty()) {
            int r = JOptionPane.showConfirmDialog(this, "¿Descartar este pedido?", "Cancelar",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
            if (r != JOptionPane.YES_OPTION) return;
        }
        dispose();
    }//GEN-LAST:event_btnCancelarActionPerformed


