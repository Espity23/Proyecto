public FormDetallePedido(java.awt.Frame parent, String titulo, String mensaje,
                         Pedido pedido, String textoAccion) {
        super(parent, true);
        initComponents();
        setTitle(titulo);
        lblMensaje.setText("<html>" + mensaje + "</html>");
        lblPedido.setText("Pedido #" + pedido.getNumero());
        lblTotal.setText("Total: " + Producto.moneda(pedido.calcularTotal()));

        DefaultTableModel modelo = (DefaultTableModel) tblDetalle.getModel();
        modelo.setRowCount(0);
        for (DetallePedido d : pedido.getDetalles()) {
            modelo.addRow(new Object[]{d.getProducto().getNombre(), d.getCantidad(),
                Producto.moneda(d.calcularSubtotal())});
        }

        if (textoAccion == null) {
            btnAccion.setVisible(false);
            btnCancelar.setText("Cerrar");
        } else {
            btnAccion.setText(textoAccion);
        }
        setLocationRelativeTo(parent);
    }

    public boolean isConfirmado() {
        return confirmado;
    }
    

